"""参考生视频「书写层」语法规范——唯一真相源。

LLM 在 step1 / step2 产出的 unit 正文与人在编辑器里写的是同一种格式，因此语法规范
只能有一份措辞：本模块的 :data:`WRITING_SYNTAX_SPEC` 由两级 prompt builder
（``build_reference_units_split_prompt`` / ``build_reference_video_prompt``）共同注入，
agent 侧文档只留概览并指向工具，前端语法提示另走 i18n 三语，均不复制全文。

放在 ``lib/reference_video/`` 与 :mod:`lib.reference_video.text_parser` 同域：规范措辞与
执行它的解析器同进同退，改语法时两者在同一目录里对照修改。
"""

from __future__ import annotations

WRITING_SYNTAX_SPEC = """每个视频单元的正文是一段**自由书写的文本**，按行书写即可。
不要写 `镜头1：` 之类的分段前缀：正文是一段连续描述，前缀没有语法含义，会被逐字带进生成提示词。

记号只有四种，与输出语言无关，可出现在正文任意位置——但**出现的先后即念白 / 口型的先后**：
按叙事时间把心声、对白、画外音写在对应画面节拍旁，不要先写完整段动作再把全部台词堆到段末。

1. `@[名称]`——引用一件登记资产（商品 / 角色 / 场景 / 道具），表示它出现在画面里。
   名称逐字取自候选表，不要发明表外的名称。角色可写 `@[角色名@造型名]` 选用衣橱中已登记的
   造型（如 `@[李明@战损]`）；省略 `@造型` 或写 `@base` 均表示基准造型。造型名必须已在该角色
   的衣橱中登记。场景 / 道具 / 商品不要写 `@造型`。
2. `@[角色名]{台词内容}`——该角色**开口**说这句话（可出口型）。花括号 `{}` 里是逐字台词；角色名
   必须是已登记的角色资产名（说话人位不要带 `@造型`——音色挂在角色身份上）。`@[名称]` 与 `{`
   之间允许有空白或一个冒号，`@[李明]{…}`、`@[李明] {…}`、`@[李明]：{…}` 三种写法等价。
3. `@[角色名%内心独白]{台词内容}`——该角色的**内心独白**（挂角色音色；心声瞬间闭嘴、不做说话口型，
   同段后续 `@[角色名]{…}` 开口对白照常口型）。`%内心独白` 写在说话人 mention 内层末尾；可与造型
   同写，如 `@[李明@战损%内心独白]{…}`（音色仍挂角色名）。多角色各写一条即可。旁白 / 解说**不要**
   用此形——旁白用下面的裸花括号。
   **心声对应瞬间的画面动作不得描写任何与发声有关的行为**（如说话、嘟囔、轻声、耳语、啧、咂嘴、
   吐舌、叹气、清嗓、哼唱等）；心声只出画外音色，画面保持闭嘴、无口部发声动作。把心声记号写在
   该静默节拍旁，不要把「啧了一声」一类口部发声动作紧挨心声。
4. `{台词内容}`——画外音 / 旁白（不指定说话人）。花括号前没有紧邻的 `@[名称]` 即为此形。

台词记号既可独占一行，也可跟在同一行的画面描述之后（`@[李明] 推开门。@[李明]{我来了。}`），
一行可以有多个记号。不进画面参考图的只有台词记号里的说话人位；某个角色若全文只出现在说话人位上，
它就只提供声音。写在记号之外的 `@[名称]` / `@[角色@造型]` 照常进入画面参考图，与同一行有没有台词无关。

结构标记不随输出语言变化：`@[]`、`%内心独白` 与花括号 `{}` 是解析器认的语法记号，任何语言的项目都逐字
保持这些记号，只有记号之间的画面描述与台词内容用项目语言书写。

硬性约束（违反即整份产出被拒）：

- 花括号只用于台词、内心独白与画外音，必须成对闭合、不嵌套、内容非空；
  **画面描述里不得出现游离的 `{` 或 `}`**——没被识别成台词记号的花括号会原样进入画面描述。
- 正文必须有画面描述，不能只有台词 / 内心独白 / 画外音。
- **发声记号按叙事时间就地填写**：心声 / 对白 / 画外音写在对应画面节拍旁；禁止把全部发声记号
  堆到段末（系统按正文出现顺序下发，堆在段末会被念成「画面演完才开口」）。开场心声写在正文靠前处。
- 语法记号一律半角：`@[名称]` 的方括号成对闭合且名称非空，台词的花括号写 `{}` 不写 `｛｝`；
  内心独白标记只能是末尾的 `%内心独白`，其它 `%…` 不成记号。
- 每个 `@[名称]` 都必须是候选表中已登记的资产名；`@[角色@造型]` 的造型须已在该角色衣橱登记；
  台词 / 内心独白的角色名同样须已登记。
- 画面描述不写外貌 / 服装 / 场景陈设 / 色调光影——静态外观由参考图承担；跨镜换装或大战损用
  `@[角色@造型]` 选衣橱，不要在正文里描写；瞬时局部妆伤（脸蹭血等）既不写外貌也不为此新建造型。
  泛指群演（老人甲 / 村民若干）直接写进描述即可，不用 `@` 引用。

示例（一个视频单元的正文）：

```
@[李明] 推开 @[酒馆] 的木门，侧身跨过门槛。@[李明]{这地方比我想的还热闹。}
他走向柜台，把 @[长剑] 横放在台面上，指节在剑鞘上叩了两下。
@[李明%内心独白]{今晚不会太平。}
{远处传来脚步声。}
```

换装示例：`@[李明@战损] 扶着墙壁站起，抬手抹去额角的汗。`
"""


